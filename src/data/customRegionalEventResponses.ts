import type { EventResponseOption, SegmentId } from '../types/game';

function boost(segments: SegmentId[], amount: number): Partial<Record<SegmentId, number>> {
  return Object.fromEntries(segments.map((id) => [id, amount])) as Partial<
    Record<SegmentId, number>
  >;
}

function penalty(segments: SegmentId[], amount: number): Partial<Record<SegmentId, number>> {
  return boost(segments, -Math.abs(amount));
}

